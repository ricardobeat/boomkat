var cache = {};
function names(loc, spec) {
  var key = loc + '/' + spec;
  if (!cache[key]) {
    var parts = spec.split(':');
    var opts = { type: parts[0], style: 'long' };
    if (parts[1] === 'std') opts.languageDisplay = 'standard';
    else if (parts[1]) opts.style = parts[1];
    cache[key] = new Intl.DisplayNames(loc, opts);
  }
  return cache[key];
}
var checked = 0;
var locales = Object.keys(DATA);
for (var i = 0; i < locales.length; i++) {
  var rows = DATA[locales[i]];
  for (var j = 0; j < rows.length; j++) {
    var row = rows[j];
    eq(names(locales[i], row[0]).of(row[1]), row[2], locales[i] + ' ' + row[0] + ' ' + row[1]);
    checked++;
  }
}
eq(locales.length, 30, 'locale count');
// Locales without a row resolve to the closest row; the language names follow it.
eq(new Intl.DisplayNames('de-CH', { type: 'language' }).of('en'), 'Englisch', 'de-CH falls back to de');
eq(new Intl.DisplayNames('de-AT', { type: 'region' }).of('DE'), 'Deutschland', 'de-AT region');
eq(new Intl.DisplayNames('de', { type: 'language' }).resolvedOptions().locale, 'de', 'resolved locale');
eq(Intl.DisplayNames.supportedLocalesOf(['de', 'ja', 'xx']).join(), 'de,ja', 'supportedLocalesOf');
// A locale whose chain leaves the row set does not borrow English names.
eq(new Intl.DisplayNames('gv', { type: 'language', fallback: 'none' }).of('de'), undefined, 'no English fallback');
eq(new Intl.DisplayNames('de', { type: 'currency', fallback: 'none' }).of('ZZZ'), undefined, 'unknown currency');
// A name that contains the pattern's parentheses gets square brackets, as ICU does.
eq(new Intl.DisplayNames('ja', { type: 'language', languageDisplay: 'standard' }).of('sw-CD'), 'スワヒリ語 (コンゴ民主共和国[キンシャサ])', 'nested brackets');
eq(new Intl.DisplayNames('zh', { type: 'language', languageDisplay: 'standard' }).of('sw-CD'), '斯瓦希里语（刚果［金］）', 'full-width brackets');
// ICU tries only the first dialect key, so a script blocks the language-region name.
eq(new Intl.DisplayNames('en', { type: 'language' }).of('en-Latn-US'), 'English (Latin, United States)', 'script blocks dialect');
