#!/usr/bin/env python3
"""Render the recorded optimized-baseline comparison; no measurements."""
from pathlib import Path
import csv,json
HERE=Path(__file__).resolve().parent
D=json.loads((HERE/'results.json').read_text())
rows=D['results']
fields=['name','kind','baseline_ms','prototype_ms','change_percent','ci_low_percent','ci_high_percent','baseline_rss_mib','prototype_rss_mib','baseline_instructions','prototype_instructions']
records=[]
for r in rows:
 s=r['summary'];k=s['metric'];ci=s['paired_bootstrap_95'];bc=r['bytecode']
 records.append(dict(name=r['name'],kind=r['kind'],baseline_ms=1000*s['baseline'][k]['median'],prototype_ms=1000*s['prototype'][k]['median'],change_percent=100*(s['ratio']-1),ci_low_percent=100*(ci[0]-1),ci_high_percent=100*(ci[1]-1),baseline_rss_mib=s['baseline']['peak_rss_bytes']['median']/1048576,prototype_rss_mib=s['prototype']['peak_rss_bytes']['median']/1048576,baseline_instructions=bc['baseline']['instructions'],prototype_instructions=bc['prototype']['instructions']))
with (HERE/'summary.csv').open('w') as f:
 w=csv.DictWriter(f,fieldnames=fields);w.writeheader();w.writerows(records)
text=[]
def line(s=''):text.append(s)
line('Flat AST constant analysis: optimized baseline comparison')
line('Baseline: '+D['baseline_revision'])
line('Prototype engine source: '+D.get('prototype_source_revision','uncommitted snapshot')+'.')
line('Measurements preceded the split commits; committed engine files match the measured snapshot.')
line('Platform: '+D['platform']+'; '+D['machine'])
line(D['compiler'].strip())
line()
line('Result: large gains are confined to deliberately constant-heavy expressions.')
line('Ordinary runtime controls and the already-folded short arithmetic case are flat.')
line('Local const propagation alone has no measurable runtime win in this kernel.')
line('Compile time improves when substantial bytecode disappears; analysis can add')
line('memory and small compile costs to code that cannot benefit. This is not a broad')
line('engine speedup, and it is not loop-invariant hoisting or statement removal.')
line()
line('Method')
line('Both binaries were built from bb4738ea using the same C3 toolchain and project')
line('targets. Baseline has no source modifications; prototype adds the reviewed diff.')
line('Optimizations are enabled on both sides. No --no-optimize measurements are used.')
line('One warmup pair, then seven measured pairs per workload, alternating AB/BA.')
line('Runtime: release CLI, complete process wall time including loading, compilation,')
line('execution and teardown. Checksums/output match across every measured process;')
line('scene output differs only in its own elapsed-time fields, which are normalized.')
line('Compile: matching O2 debug CLIs, -d --check, internal compiler timer excluding')
line('heap/VM startup, execution and teardown. Whole-process wall and CPU time are')
line('also retained in raw/*.json. These debug-target compile numbers should not be')
line('mixed with release execution times as if they were one identical feature profile.')
line('Peak RSS: per-child wait4 ru_maxrss, bytes on macOS; table shows median peak RSS.')
line('No affinity, frequency lock, system-wide isolation or outlier removal. Bootstrap')
line('intervals resample the seven paired observations (5000 deterministic resamples);')
line('they describe this sample, not independent replication across hardware/days.')
line()
line('Median runtime (ms; negative change is faster)')
line(f"{'case':30} {'base':>10} {'prototype':>10} {'change':>9} {'paired 95% range':>22} {'RSS MiB base -> proto':>24}")
for r in records:
 if r['kind']!='runtime':continue
 line(f"{r['name']:30} {r['baseline_ms']:10.3f} {r['prototype_ms']:10.3f} {r['change_percent']:+8.1f}% {r['ci_low_percent']:+8.1f}%..{r['ci_high_percent']:+6.1f}% {r['baseline_rss_mib']:10.2f} -> {r['prototype_rss_mib']:6.2f}")
line()
line('Median compile-only time (ms, internal compiler timer)')
line(f"{'case':30} {'base':>10} {'prototype':>10} {'change':>9} {'paired 95% range':>22} {'RSS MiB base -> proto':>24}")
for r in records:
 if r['kind']!='compile':continue
 line(f"{r['name']:30} {r['baseline_ms']:10.3f} {r['prototype_ms']:10.3f} {r['change_percent']:+8.1f}% {r['ci_low_percent']:+8.1f}%..{r['ci_high_percent']:+6.1f}% {r['baseline_rss_mib']:10.2f} -> {r['prototype_rss_mib']:6.2f}")
line()
line('Optimized bytecode instruction counts (complete function tree; 4 bytes/instruction)')
for r in rows:
 bc=r['bytecode'];a=bc['baseline'];b=bc['prototype']
 extra=''
 if a['kernel'] and b['kernel']:extra=f"; kernel {a['kernel'][0]['instructions']} -> {b['kernel'][0]['instructions']}"
 line(f"{r['name']:30} {a['instructions']:8} -> {b['instructions']:8}{extra}")
line('Counts exclude constant-pool data, metadata, allocator capacity and source text.')
line('Bounded runtime dumps are committed in bytecode/*.json.gz; all opcode counts are in results.json.')
line('Large compile dumps remain locally available but are ignored; regenerate them from the same inputs.')
line()
line('Interpretation and limits')
line('* Long numeric: synthetic 128-term constant subtree exceeds the old 32-node')
line('  probe. Kernel shrinks 131 -> 4 instructions. This deliberately amplifies an')
line('  upper-bound case by calling it a million times; it is not representative JS.')
long=next(x for x in rows if x['name']=='long_numeric')['summary']
line(f"  Its baseline has MAD {long['baseline']['wall_s']['mad']/long['baseline']['wall_s']['median']*100:.1f}% (range {long['baseline']['wall_s']['min']*1000:.1f}..{long['baseline']['wall_s']['max']*1000:.1f} ms), so the precise ratio is noisy; the large gain remains clear.")
line('* Primitive/bitwise: boolean/null coercions and fixed string-to-number inputs')
line('  disappear from a repeatedly called synthetic kernel (17 -> 2 instructions).')
line('* Literal strings: a constant suffix is precomputed, while the varying prefix')
line('  and resulting concatenation remain dynamic (kernel 10 -> 3). The parameterized')
line('  string control stays 6 instructions and its timing is flat.')
line('* Local const: kernel shrinks only 8 -> 7 instructions. Baseline already uses')
line('  immediate arithmetic and register bindings. Prototype still initializes three')
line('  constants (three LDINTs); call/loop costs dominate. The runtime +0.3% is noise,')
line('  with an interval spanning improvement and regression. The explicit-constant')
line('  kernel remains only 3 instructions in both builds.')
line('* Old short constants: the old optimizer already handles these. Both kernels')
line('  are 3 instructions; there is no incremental benefit here.')
line('* Existing arithmetic, array, object, recursion and scene workloads keep exactly')
line('  the same bytecode counts. Their timing changes are within roughly +/-1%, with')
line('  paired intervals spanning zero; no broad runtime change is established.')
line('* Generated compile targets replicate simple functions: 1000 long-numeric, 3000')
line('  local-const/string/dynamic functions, 2000 literal-array functions, and 50 copies')
line('  of the existing scene program in wrappers. These are scalability probes, not')
line('  real bundled applications. Larger library corpora were absent from this worktree;')
line('  nothing was downloaded. The existing scene file is also measured unchanged.')
line('* Dynamic compile control keeps 27001 instructions but median peak RSS increases')
line('  about 0.53 MiB (10.70 -> 11.23). Local const compile rises about 0.58 MiB despite')
line('  a small time/code reduction. Long arithmetic and repeated strings shrink enough')
line('  code to offset analysis storage in observed RSS. RSS is process-wide and cannot')
line('  attribute individual allocations; small runtime RSS changes are not heap savings.')
line('* Literal/scene compile controls are about +1.2%/+0.8% in this run. The literal')
line('  case skips the fact allocation but still pays the candidate scan. These small')
line('  observed costs warrant follow-up rather than an overall compile-speed claim.')
line('* Existing scene compile is 0.330 -> 0.338 ms; an 8 us difference at that scale')
line('  is too small to generalize.')
line('* Facts cost sizeof(TVal) per AST node (8 bytes here, 16 with NONANBOX). Const')
line('  eligibility additionally uses a transient 4-byte node map plus binding entries;')
line('  resolver refs are released before fact construction. String roots are bounded')
line('  at 128 strings, 16 KiB retained text and 1 KiB/string, plus root/header storage.')
line('  All analysis storage is released before final bytecode copying. Budgets and')
line('  allocation fallback preserve ordinary generation. These measurements use NANBOX.')
base=D['binaries']['baseline']['runtime']['bytes'];proto=D['binaries']['prototype']['runtime']['bytes']
line(f'* Release executable size: {base} -> {proto} bytes (+{proto-base}, {(proto/base-1)*100:.2f}%).')
line('* Conservative scope exclusions remain: captured/dynamic bindings, globals/module')
line('  consts, destructuring, for-head/switch declarations and unknown discarded arms.')
line('  No statement/hoisting transformation, speculative algebra, CSE or generic IR.')
line()
line('Artifacts and reproduction')
line('  prepare.py                  regenerate workload sources and manifest')
line('  run.py                      benchmark prebuilt baseline/prototype binaries')
line('  summarize.py                render this report and summary.csv from results.json')
line('  manifest.json               paths and workload categories')
line('  results.json                summaries, source/binary hashes and bytecode counts')
line('  raw/*.json                  all seven samples and warmups, outputs, RSS/CPU/wall')
line('  bytecode/*.json.gz          committed runtime dumps; large compile dumps ignored')
line('  prototype.patch             ignored historical patch, reproducible from baseline/source commits')
line('  pilot.json                  ignored preliminary screen, not used in this report')
line('Large generated compile sources/dumps are intentionally excluded from Git; all')
line('recorded raw measurements, source hashes and instruction/opcode counts are committed.')
line('prepare.py regenerates sources; boomkat_debug --format json SOURCE regenerates')
line('a structured dump. run.py regenerates the complete experiment when measuring again.')
line('Build (separate worktrees; no merge or main checkout edits):')
line('  git worktree add --detach /private/tmp/boomkat-flat-ast-baseline bb4738ea')
line('  make -C /private/tmp/boomkat-flat-ast-baseline out/boomkat out/boomkat_debug')
line('  make -B -C /private/tmp/boomkat-flat-ast-prototype out/boomkat out/boomkat_debug')
line('  python3 experiments/flat-ast/prepare.py')
line('  python3 experiments/flat-ast/run.py --pairs 7')
line('  python3 experiments/flat-ast/summarize.py')
line('No Test262 commands, suites or runners were used.')
(HERE/'report.txt').write_text('\n'.join(text)+'\n')
print('Wrote',HERE/'report.txt','and summary.csv')
