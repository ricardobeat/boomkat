#!/usr/bin/env python3
"""Generate src/builtins/intl_available_data.c3: the tags that CLDR ships a locale for.

Intl.DateTimeFormat("de-DE").resolvedOptions().locale is "de-DE" because ICU has a de_DE locale,
while "de-XX" resolves to "de". The table lists, for every language with a locale row, the
lang[-Script][-REGION] locales in ICU's data/locales directory. Variants such as ca_ES_VALENCIA
are left out: the engine's resolved tags carry no variant.

    python3 scripts/generate_intl_available.py --source /path/to/icu/source
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from generate_intl_locales import LOCALES


def locale_tags(source, langs):
    """ICU locale ids under data/locales with a script or region, as BCP 47 tags. An alias that
    only adds the likely script (zh_CN for zh_Hans_CN) is a locale of its own; one that renames
    a region (en_RH for en_ZW) is left out, as BCP 47 canonicalization rewrites that region."""
    tags = []
    for path in sorted((source / 'data' / 'locales').glob('*.txt')):
        fields = split_id(path.stem)
        if fields is None or fields[0] not in langs or fields == (fields[0], '', ''):
            continue
        alias = re.search(r'"%%ALIAS"\{"([^"]*)"\}', path.read_text(encoding='utf-8-sig'))
        if alias:
            target = split_id(alias.group(1))
            if target is None or target[0] != fields[0] or target[2] != fields[2]:
                continue
        tags.append('-'.join(p for p in fields if p))
    return tags


def split_id(ident):
    """(lang, script, region) of an ICU locale id, or None when it carries a variant."""
    parts = ident.split('_')
    script = parts[1] if len(parts) > 1 and len(parts[1]) == 4 else ''
    rest = parts[1 + bool(script):]
    region = rest[0] if rest else ''
    if len(rest) > 1 or (region and len(region) not in (2, 3)):
        return None
    return (parts[0], script, region)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--source', type=Path, required=True)
    args = parser.parse_args()
    langs = {ident.split('_')[0] for ident in LOCALES}
    tags = locale_tags(args.source, langs)
    lines = ['// Generated by scripts/generate_intl_available.py --source <icu/source>. Do not edit.',
             'module boomkat::builtins;', '',
             '// Tags with a CLDR locale: lang[-Script][-REGION], NUL-separated.',
             'const char[*] INTL_AVAILABLE_TAGS = "' + ''.join(tag + '\\0' for tag in tags) + '";', '']
    Path('src/builtins/intl_available_data.c3').write_text('\n'.join(lines))
    print(f'{len(tags)} tags', file=sys.stderr)


if __name__ == '__main__':
    main()
