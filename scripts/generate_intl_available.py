#!/usr/bin/env python3
"""Generate src/builtins/intl_available_data.c3: the tags that CLDR ships a locale for.

Intl.DateTimeFormat("de-DE").resolvedOptions().locale is "de-DE" because ICU has a de_DE locale,
while "de-XX" resolves to "de". The table lists those tags for every language with a locale row.
It is probed from a Node.js build (ICU 77 or newer) by resolving each candidate tag, so run it with
`node` on PATH from the repository root. Do not hand-edit the output.
"""
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from generate_intl_locales import LOCALES

PROBE = r"""
const [langs, scripts] = JSON.parse(process.argv[1]);
const regions = [''];
for (let a = 65; a < 91; a++) for (let b = 65; b < 91; b++) regions.push(String.fromCharCode(a, b));
for (let n = 1; n < 1000; n++) regions.push(String(n).padStart(3, '0'));
const found = new Set();
for (const lang of langs) {
  for (const script of ['', ...scripts]) {
    for (const region of regions) {
      if (!script && !region) continue;
      const tag = [lang, script, region].filter(Boolean).join('-');
      const dtf = new Intl.DateTimeFormat(tag).resolvedOptions().locale;
      const nf = new Intl.NumberFormat(tag).resolvedOptions().locale;
      if (dtf === tag && nf === tag) found.add(tag);
      else if (dtf === tag || nf === tag) throw new Error('services disagree on ' + tag);
    }
  }
}
console.log(JSON.stringify([...found]));
"""

SCRIPTS = ['Latn', 'Cyrl', 'Arab', 'Hans', 'Hant']


def main():
    langs = sorted({ident.split('_')[0] for ident in LOCALES})
    out = subprocess.run(['node', '-e', PROBE, json.dumps([langs, SCRIPTS])], check=True,
                         capture_output=True, text=True).stdout
    tags = sorted(json.loads(out))
    entries = []
    for tag in tags:
        parts = tag.split('-')
        lang = parts[0]
        script = parts[1] if len(parts) > 1 and len(parts[1]) == 4 else ''
        region = parts[-1] if len(parts) > 1 and len(parts[-1]) != 4 else ''
        entries.append((lang, script, region))
    lines = ['// Generated by scripts/generate_intl_available.py. Do not edit.',
             'module boomkat::builtins;', '',
             '// Tags with a CLDR locale: lang[-Script][-REGION], NUL-separated.',
             'const char[*] INTL_AVAILABLE_TAGS = "' + ''.join('-'.join(p for p in e if p) + '\\0' for e in entries) + '";', '']
    Path('src/builtins/intl_available_data.c3').write_text('\n'.join(lines))
    print(f'{len(entries)} tags', file=sys.stderr)


if __name__ == '__main__':
    main()
