#!/usr/bin/env python3
"""Generate the Umm al-Qura table behind the islamic-umalqura calendar from ICU 78.3.

    cc scripts/intl/dump_umalqura.c -I$ICU/include -L$ICU/lib -licuuc -licui18n -licudata
    ./a.out > umalqura.txt
    python3 scripts/generate_umalqura.py umalqura.txt

writes src/lib/temporal/umalqura_data.c3. Each Hijri year ICU tabulates becomes one ushort:
bit k (0..11) is set when month k+1 has 30 days rather than 29, and bits 12-13 hold the
year's first day relative to the tabular islamic-civil year start, plus one. Years outside
the table use islamic-civil, which the table meets without a gap at both ends.
"""
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src/lib/temporal/umalqura_data.c3"

# 1 Muharram of a Hijri year under islamic-civil, in days since 1970-01-01 (ICU islamcal.cpp).
def civil_start(year):
    return 354 * (year - 1) + (11 * year + 3) // 30 + 1948440 - 2440588


def main():
    rows = []
    for line in open(sys.argv[1]):
        year, start, months = line.rstrip("\n").split("\t")
        rows.append((int(year), int(start), [int(m) for m in months.split()]))
    for (year, start, months), (_, next_start, _) in zip(rows, rows[1:]):
        if start + sum(months) != next_start:
            sys.exit(f"year {year} does not end where {year + 1} starts")
    first, last = rows[0][0], rows[-1][0]
    if rows[0][1] != civil_start(first) or rows[-1][1] + sum(rows[-1][2]) != civil_start(last + 1):
        sys.exit("the table does not meet islamic-civil at its ends")

    words = []
    for year, start, months in rows:
        delta = start - civil_start(year)
        if not -1 <= delta <= 1 or any(m not in (29, 30) for m in months):
            sys.exit(f"year {year} does not fit the packed form")
        bits = sum(1 << k for k, m in enumerate(months) if m == 30)
        words.append(bits | (delta + 1) << 12)

    lines = [
        "// Generated by scripts/generate_umalqura.py from ICU 78.3. Do not edit.",
        "module boomkat::lib::temporal;",
        "",
        f"const long UMALQURA_FIRST_YEAR = {first};",
        f"const long UMALQURA_LAST_YEAR = {last};",
        "",
        "// Bit k: month k+1 has 30 days. Bits 12-13: the year's first day less the",
        "// islamic-civil one, plus one.",
        f"const ushort[{len(words)}] UMALQURA_YEARS = {{",
    ]
    for i in range(0, len(words), 10):
        lines.append("    " + " ".join(f"0x{w:04x}," for w in words[i:i + 10]))
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
