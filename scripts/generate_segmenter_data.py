#!/usr/bin/env python3
"""Generate Unicode 17 segmentation tables with the regex package (2026.7.19).

regex supplies the Unicode Character Database properties used by UAX #29.
Run from the repository root; the generated file is checked in.
"""
from pathlib import Path
import regex

text = ''.join(map(chr, range(0x110000)))
properties = {
    'G': ['CR', 'LF', 'Control', 'Extend', 'ZWJ', 'Regional_Indicator', 'Prepend', 'SpacingMark', 'L', 'V', 'T'],
    'W': ['CR', 'LF', 'Newline', 'Extend', 'ZWJ', 'Regional_Indicator', 'Format', 'Katakana', 'Hebrew_Letter', 'ALetter', 'Single_Quote', 'Double_Quote', 'MidNumLet', 'MidLetter', 'MidNum', 'Numeric', 'ExtendNumLet', 'WSegSpace'],
    'S': ['CR', 'LF', 'Sep', 'Extend', 'Format', 'Sp', 'Lower', 'Upper', 'OLetter', 'Numeric', 'ATerm', 'STerm', 'Close', 'SContinue'],
    'I': ['Consonant', 'Extend', 'Linker'],
    'E': ['Extended_Pictographic'],
}
keys = {'G': 'Grapheme_Cluster_Break', 'W': 'Word_Break', 'S': 'Sentence_Break', 'I': 'Indic_Conjunct_Break'}
lines = ['// Generated by scripts/generate_segmenter_data.py; Unicode 17 / UAX #29.', 'module boomkat::builtins;', '', 'struct SegmentRange { uint first; uint last; uint value; }', '']
for kind, values in properties.items():
    ranges = []
    for number, value in enumerate(values, 1):
        lines.append(f'const uint SEG_{kind}_{value.upper()} = {number};')
        prop = f'{keys[kind]}={value}' if kind in keys else value
        ranges.extend((m.start(), m.end()-1, number) for m in regex.finditer(r'\p{' + prop + '}+', text))
    ranges.sort()
    lines.append(f'const SegmentRange[{len(ranges)}] SEG_{kind}_RANGES = {{')
    lines.extend(f'    {{0x{lo:X}, 0x{hi:X}, {value}}},' for lo, hi, value in ranges)
    lines.extend(['};', ''])
lines.extend(['const uint SEG_G_LV = 12;', 'const uint SEG_G_LVT = 13;', ''])
Path('src/builtins/intl_segment_data.c3').write_text('\n'.join(lines))
