#!/usr/bin/env python3
"""Generate the calendar names DateTimeFormat uses for the Chinese, Hebrew and islamic-civil
calendars from ICU 78.3 / CLDR 48 locale data.

Writes src/builtins/intl_lunar_names.c3. Run from the repository root:
    python3 scripts/generate_intl_calendar_names.py --source /path/to/icu/source
"""
import argparse
import re
from pathlib import Path


def block_strings(text, locale_marker, calendar_key, child_key, mode):
    """The quoted strings in one calendar's child block, such as chinese / monthNames / wide."""
    i = text.find(locale_marker)
    seg = text[i:]
    j = seg.find(calendar_key)
    if mode == 'years':
        k = seg.find('abbreviated{', j)
    else:
        k = seg.find(child_key, j)
    e = seg.find('}', k)
    return re.findall(r'"([^"]+)"', seg[k:e])


def c3_string_array(name, items, per_line=4):
    lines = [f'const String[*] {name} = {{']
    for i in range(0, len(items), per_line):
        lines.append('    ' + ', '.join(f'"{s}"' for s in items[i:i + per_line]) + ',')
    lines.append('};')
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--out', type=Path, default=Path('src/builtins/intl_lunar_names.c3'))
    args = parser.parse_args()
    locales = args.source / 'data/locales'
    if '#define U_ICU_VERSION "78.3"' not in (args.source / 'common/unicode/uvernum.h').read_text():
        parser.error('Use ICU 78.3 sources')
    en = (locales / 'en.txt').read_text(encoding='utf8')
    zh = (locales / 'zh.txt').read_text(encoding='utf8')
    root = (locales / '../locales/root.txt').read_text(encoding='utf8')

    chinese = '        chinese{'
    tables = [
        ('LUNAR_YEAR_NAMES_ZH', block_strings(zh, chinese, 'years{', 'wide{', 'years')),
        ('LUNAR_YEAR_NAMES_EN', block_strings(root, chinese, 'years{', 'wide{', 'years')),
        ('LUNAR_MONTH_NAMES_EN', block_strings(en, chinese, 'monthNames{', 'wide{', 'month')),
        ('LUNAR_MONTH_NAMES_ZH', block_strings(zh, chinese, 'monthNames{', 'wide{', 'month')),
    ]
    hijri = block_strings(en, '        islamic{', 'monthNames{', 'wide{', 'month')
    hebrew = block_strings(en, '        hebrew{', 'monthNames{', 'wide{', 'month')
    assert len(hijri) == 12 and len(hebrew) == 14, (len(hijri), len(hebrew))
    for name, items in tables:
        assert len(items) == (60 if 'YEAR' in name else 12), (name, len(items))

    blocks = [
        '// Generated by scripts/generate_intl_calendar_names.py from ICU 78.3 / CLDR 48 locale data.\n'
        '// Do not edit.\nmodule boomkat::builtins;',
        '// Cyclic year names (sexagenary, index (year - 4) mod 60) and wide month names for the Chinese calendar.\n'
        + '\n'.join(c3_string_array(name, items) for name, items in tables),
        '// Islamic civil month names, English (the islamic CLDR names apply to islamic-civil).\n'
        + c3_string_array('LUNAR_MONTH_NAMES_HIJRI_EN', hijri),
        '// Hebrew month names, English, as ICU lists them: the common-year order skips "Adar II".\n'
        + c3_string_array('HEBREW_MONTH_NAMES_EN', hebrew),
    ]
    args.out.write_text('\n\n'.join(blocks) + '\n', encoding='utf8')
    print(f'{args.out}: {len(tables)} tables, islamic-civil and Hebrew month names')


if __name__ == '__main__':
    main()
