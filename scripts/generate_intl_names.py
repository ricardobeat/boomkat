#!/usr/bin/env python3
"""Generate the English display names behind Intl.DisplayNames from ICU 78.3 / CLDR 48.

Names of languages (with the dialect names), scripts, regions, variants,
calendar types and date-time fields go into one sorted table. Each key carries
a one-letter kind prefix; short-style variants have their own kind:

    l language   L language, short     s script   S script, short
    r region     R region, short       v variant  c calendar type   f field

Names live in one NUL-separated pool addressed by 16-bit offsets, so the
tables sit in read-only data and need no load-time fixups. Currency names
reuse the NumberFormat currency tables.
"""
import argparse
from pathlib import Path
from generate_intl_english import resource

CALENDAR_TYPE = {'gregorian': 'gregory', 'ethiopic-amete-alem': 'ethioaa'}
FIELDS = ['era', 'year', 'quarter', 'month', 'week', 'weekday', 'day', 'dayperiod', 'hour', 'minute', 'second', 'zone']


def first(value):
    return value[0] if isinstance(value, list) else value


def c3_array(name, ctype, values, per_line, comment):
    lines = [comment, f'const {ctype}[*] {name} = {{']
    for i in range(0, len(values), per_line):
        lines.append('    ' + ', '.join(str(v) for v in values[i:i + per_line]) + ',')
    lines.append('};')
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--out', type=Path, default=Path('src/builtins/intl_names_data.c3'))
    args = parser.parse_args()
    if '#define U_ICU_VERSION "78.3"' not in (args.source/'common/unicode/uvernum.h').read_text():
        parser.error('Use ICU 78.3 sources')
    lang = resource(args.source/'data/lang/en.txt')
    region = resource(args.source/'data/region/en.txt')
    locale = resource(args.source/'data/locales/en.txt')

    entries = {}
    def add(kind, table, rename=lambda k: k):
        for key, value in table.items():
            entries[kind + rename(key)] = first(value)
    add('l', lang['Languages'], lambda k: k.replace('_', '-'))
    add('L', lang['Languages%short'], lambda k: k.replace('_', '-'))
    add('s', lang['Scripts'])
    add('S', lang['Scripts%short'])
    add('r', region['Countries'])
    add('R', region['Countries%short'])
    add('v', lang['Variants'])
    add('c', lang['Types']['calendar'], lambda k: CALENDAR_TYPE.get(k, k))
    for field in FIELDS:
        for suffix in ('', '-short', '-narrow'):
            entries['f' + field + suffix] = first(locale['fields'][field + suffix]['dn'])

    keys = sorted(entries)
    pool = bytearray(b'\0')
    at = {}
    def name_offset(name):
        if name not in at:
            at[name] = len(pool)
            pool.extend(name.encode() + b'\0')
        return at[name]
    key_blob = bytearray()
    key_at, values = [], []
    for k in keys:
        key_at.append(len(key_blob))
        key_blob.extend(k.encode() + b'\0')
        values.append(name_offset(entries[k]))
    assert len(pool) < 65536 and len(key_blob) < 65536

    out = [
        c3_array('INTL_NAME_KEYS', 'char', list(key_blob), 24, '// Sorted NUL-terminated keys: a kind letter, then the code.'),
        c3_array('INTL_NAME_KEY_AT', 'ushort', key_at, 12, '// Offset of each key in INTL_NAME_KEYS.'),
        c3_array('INTL_NAME_VALUE_AT', 'ushort', values, 12, '// Offset of each key\'s name in INTL_NAME_POOL.'),
        c3_array('INTL_NAME_POOL', 'char', list(pool), 24, '// NUL-separated display names.'),
    ]
    header = ('// Generated by scripts/generate_intl_names.py from ICU 78.3 / CLDR 48.\n'
              '// Do not edit.\nmodule boomkat::builtins;\n\n')
    args.out.write_text(header + '\n\n'.join(out) + '\n')
    print(f'{args.out}: {len(keys)} names, pool {len(pool)} bytes, keys {len(key_blob)} bytes')


if __name__ == '__main__':
    main()
